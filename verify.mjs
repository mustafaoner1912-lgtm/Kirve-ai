import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8');
const html = read('public/index.html');
const js = read('public/app.js');
const server = read('server.js');
const manifest = JSON.parse(read('public/manifest.webmanifest'));
const pkg = JSON.parse(read('package.json'));
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]);
const usedIds = [...js.matchAll(/\$\(\"([^\"]+)\"\)/g)].map((m) => m[1]);
const missingBindings = [...new Set(usedIds.filter((id) => !ids.includes(id)))];
if (missingBindings.length) throw new Error(`JavaScript references missing HTML ids: ${missingBindings.join(', ')}`);
const duplicates = ids.filter((id, index) => ids.indexOf(id) !== index);
if (duplicates.length) throw new Error(`Duplicate HTML ids: ${duplicates.join(', ')}`);
const required = ['chat','prompt','send','status','newChat','tasksToggle','taskCount','logout','tasksPanel','closeTasks','tabTasks','tabMemories','tabChats','taskList','memoryList','chatList','mic','speaker','attach','filePicker','attachmentTray','backupDownload'];
const missing = required.filter((id) => !ids.includes(id));
if (missing.length) throw new Error(`Missing HTML ids: ${missing.join(', ')}`);
for (const id of ['newChat','tabChats','chatList']) if (!js.includes(`$("${id}")`)) throw new Error(`Missing JS binding for ${id}`);
for (const file of ['public/icon-192.png','public/icon-512.png','public/apple-touch-icon.png']) if (!fs.existsSync(path.join(root,file))) throw new Error(`Missing PWA asset: ${file}`);
for (const icon of manifest.icons) if (!fs.existsSync(path.join(root, 'public', path.basename(icon.src)))) throw new Error(`Missing manifest icon: ${icon.src}`);
for (const route of ['/api/chats', '/api/memories', '/api/realtime/session', '/api/chats/:id/files', '/api/backup', '/health/ready']) if (!server.includes(route)) throw new Error(`Missing server route: ${route}`);
if (pkg.version !== '0.5.7') throw new Error('Unexpected package version.');
if (!fs.existsSync(path.join(root, 'Dockerfile'))) throw new Error('Missing Dockerfile.');
if (!fs.existsSync(path.join(root, 'scripts/setup.mjs'))) throw new Error('Missing local setup wizard.');
if (!fs.existsSync(path.join(root, 'KIRVE-AI-KUR.bat'))) throw new Error('Missing Windows installer launcher.');
if (!fs.existsSync(path.join(root, 'lib/security.js'))) throw new Error('Missing security helpers.');
if (!JSON.parse(read('package.json')).scripts['start:production'].includes('preflight')) throw new Error('Production start must run preflight.');
if (!read('render.yaml').includes('npm run start:production')) throw new Error('Render must use guarded production start.');
console.log('KİRVE AI v0.5.7 verification passed: UI bindings, PWA assets, security helpers, API routes, and package metadata.');
